// Deterministic local fixtures and pure comparison helpers for the experimental
// FRAME/12 Agent Approval Inbox prototype (/experiments/agent-approval).
//
// No runtime dependency on the `ai` package is added in this prototype.
// The `ExperimentalToolApprovalRequest` interface mirrors Vercel AI SDK 7's
// `toolApproval` request fields (`approvalId`, `toolCallId`, `toolName`, `input`)
// emitted when a tool is configured with `toolApproval: { [toolName]: 'user-approval' }`
// and pauses in `state === 'approval-requested'`, answered on the client via
// `addToolApprovalResponse({ id: approvalId, approved, reason })`.

export type ApprovalScenarioId = 'apr-ordinary-25' | 'apr-misleading-2500' | 'apr-expired-stale';

export type ApprovalLifecycleState =
  | 'approval-requested'
  | 'approved'
  | 'rejected'
  | 'expired'
  | 'superseded';

export type ClockPresetId = 'clock-default' | 'clock-early' | 'clock-late';

export interface ClockPreset {
  id: ClockPresetId;
  label: string;
  unit: string;
  iso: string;
  epochMs: number;
  caption: string;
}

export interface ApprovalClaimMap {
  orderId: string;
  amountUsd: number;
  currency: string;
  destination: string;
  reasonCode: string;
}

export interface ApprovalToolInput {
  orderId: string;
  amountUsd: number;
  amountCents: number;
  currency: string;
  destination: string;
  reasonCode: string;
  idempotencyKey: string;
  auditMemo: string;
}

export interface ApprovalFieldSpec {
  key: keyof ApprovalClaimMap;
  label: string;
}

export interface TrustedOrderFacts {
  orderId: string;
  customerId: string;
  currency: string;
  orderTotalCents: number;
  priorRefundsCents: number;
  originalDestination: string;
  originalDestinationLabel: string;
  activeResolutionStatus?: 'OPEN' | 'REPLACEMENT_SHIPMENT_QUEUED';
  activeResolutionDetail?: string;
  supersededReasonCode?: string;
  untrustedContextWarning?: string;
}

export interface TrustedPolicyFacts {
  policyId: string;
  maxCourtesyRefundCents: number;
  maxCourtesyLabel?: string;
  requireOriginalPaymentDestination: boolean;
  allowedReasonCodes: string[];
}

export interface TrustedFixtureFact {
  label: string;
  value: string;
  matchesProposedInput: boolean;
}

export interface TrustedFixtureRecord {
  recordId: string;
  sourceFile: string;
  title: string;
  snapshotAt: string;
  orderFacts?: TrustedOrderFacts;
  policyFacts?: TrustedPolicyFacts;
}

export interface EvaluatedTrustedRecord {
  recordId: string;
  sourceFile: string;
  title: string;
  snapshotAt: string;
  facts: TrustedFixtureFact[];
}

export interface ConversationMeta {
  conversationId: string;
  channel: string;
  customerHandle: string;
  subject: string;
  agentModel: string;
  turnNumber: number;
  latestTurnNumber: number;
  changeSummary?: string;
}

export interface ExperimentalToolApprovalRequest {
  /** Scenario identifier used for deterministic UI selection and tests */
  scenarioId: ApprovalScenarioId;
  /** Short badge code for the inbox queue */
  scenarioCode: string;
  /** Short title shown in the inbox list */
  scenarioTitle: string;
  /** Mirrors AI SDK 7 `part.approval.id` passed to `addToolApprovalResponse({ id })` */
  approvalId: string;
  /** Mirrors AI SDK 7 `part.toolCallId` */
  toolCallId: string;
  /** Mirrors AI SDK 7 `part.toolName` (or `tool-${toolName}` part type) */
  toolName: string;
  /** Mirrors AI SDK 7 `part.input` (the actual structured arguments sent to the tool) */
  input: ApprovalToolInput;
  /** Structured claims emitted alongside the agent's prose (never parsed from prose) */
  claims: ApprovalClaimMap;
  /** Field-by-field comparison metadata against trusted local fixture records */
  fieldSpecs: ApprovalFieldSpec[];
  /** Untrusted conversational prose generated by the agent */
  agentExplanation: string;
  /** Independent supporting context loaded from labeled local fixture records */
  trustedRecords: TrustedFixtureRecord[];
  /** Simulated AI conversation metadata */
  conversation: ConversationMeta;
  /** ISO-8601 creation timestamp */
  requestedAt: string;
  /** ISO-8601 expiration timestamp for the approval window */
  expiresAt: string;
  /** Current local demonstration status */
  status: ApprovalLifecycleState;
  /** Plain-language explanation of what would happen in a real system after approval */
  postApprovalEffect: {
    targetSystem: string;
    operationSummary: string;
    reversibility: string;
    sdkCallbackPreview: string;
  };
}

export interface EvaluatedFieldComparison {
  key: keyof ApprovalClaimMap;
  label: string;
  actualInputRaw: string | number;
  actualInputDisplay: string;
  claimedRaw: string | number;
  claimedDisplay: string;
  trustedExpectedDisplay: string;
  trustedSourceId: string;
  trustedConstraintNote: string;
  claimMatchesInput: boolean;
  trustedMatchesInput: boolean;
  isMismatch: boolean;
  mismatchSummary: string | null;
}

export interface EvaluatedApprovalRequest {
  request: ExperimentalToolApprovalRequest;
  effectiveStatus: ApprovalLifecycleState;
  isExpired: boolean;
  isSuperseded: boolean;
  comparisons: EvaluatedFieldComparison[];
  mismatches: EvaluatedFieldComparison[];
  evaluatedTrustedRecords: EvaluatedTrustedRecord[];
  requiredAcknowledgmentText: string | null;
  canApproveOrReject: boolean;
  disableApproveReason: string | null;
  remainingLabel: string;
}

