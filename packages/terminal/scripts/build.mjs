#!/usr/bin/env node
/**
 * Builds @frame12/terminal deterministically:
 *   1. derives src/core/tokens.generated.ts from the installed @frame12/tokens (build-time tokens);
 *   2. `tsc -p tsconfig.json` compiles src/ to dist/ (.js + .d.ts);
 *   3. generates schema/events.schema.json from the contract's declarative EVENT_SPEC.
 *
 * `--check` regenerates everything into a temporary directory and fails if the committed
 * tokens.generated.ts, dist/ or schema/ differ (dist/ is committed, like the other packages).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const require = createRequire(path.join(PKG_ROOT, 'package.json'));
const tsc = require.resolve('typescript/bin/tsc');
const check = process.argv.includes('--check');

const TOKENS_GENERATED = path.join(PKG_ROOT, 'src/core/tokens.generated.ts');
const SCHEMA_PATH = path.join(PKG_ROOT, 'schema/events.schema.json');

function listFiles(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

async function renderTokensModule() {
  const tokensPkg = JSON.parse(fs.readFileSync(require.resolve('@frame12/tokens/package.json'), 'utf8'));
  const { tokens } = await import(pathToFileURL(require.resolve('@frame12/tokens')).href);
  const pick = (theme) => {
    const t = tokens[theme];
    const out = {
      desk: t.desk,
      sheet: t.sheet,
      panel: t.panel,
      paper: t.sheet,
      ink: t.ink,
      'ink-2': t['ink-2'],
      rule: t.rule,
      grid: t.grid,
      marker: t.marker,
      'marker-ink': t['marker-ink'],
    };
    for (const [k, v] of Object.entries(out)) {
      if (!/^#[0-9a-f]{6}$/i.test(v)) throw new Error(`@frame12/tokens ${theme}.${k} is not #rrggbb: ${v}`);
    }
    return out;
  };
  const px = (v) => {
    const n = Number(String(v).replace(/px$/, ''));
    if (!Number.isFinite(n)) throw new Error(`Bad gutter ${v}`);
    return n;
  };
  const palette = { light: pick('light'), dark: pick('dark') };
  const gutters = { pair: px(tokens.gutters.pair), scene: px(tokens.gutters.scene), change: px(tokens.gutters.change) };
  const motion = { fps: tokens.motion.fps, pose: tokens.motion.pose };
  return `/* Generated by scripts/build.mjs from @frame12/tokens@${tokensPkg.version} — do not edit by hand. */
/** The @frame12/tokens version these values were derived from. */
export const TOKENS_PACKAGE_VERSION = ${JSON.stringify(tokensPkg.version)};

/** Paper Light and Flashback Dark colors (\`paper\` is \`sheet\`). */
export const tokenPalette = ${JSON.stringify(palette, null, 2)} as const;

/** Legal gutters in CSS pixels. */
export const tokenGutterPx = ${JSON.stringify(gutters, null, 2)} as const;

/** 12 fps "on twos" motion. */
export const tokenMotion = ${JSON.stringify(motion, null, 2)} as const;
`;
}

async function renderSchema(distDir) {
  const contract = await import(pathToFileURL(path.join(distDir, 'core/contract.js')).href + `?t=${Date.now()}`);
  const { EVENT_SPEC, EVENT_BASE_SPEC, OBJECT_SPEC, EVENT_TYPES, ID_PATTERN, PRESENTATION_LABEL_PATTERN, SCHEMA_VERSION, TIMESTAMP_PATTERN } = contract;
  const field = (spec) => {
    switch (spec.kind) {
      case 'string':
        return { type: 'string', ...(spec.nonEmpty ? { minLength: 1, pattern: '\\S' } : {}), ...(spec.maxLength !== undefined ? { maxLength: spec.maxLength } : {}) };
      case 'id':
        return { $ref: '#/$defs/Id' };
      case 'timestamp':
        return { $ref: '#/$defs/Timestamp' };
      case 'integer':
        return { type: 'integer', ...(spec.min !== undefined ? { minimum: spec.min } : {}) };
      case 'number':
        return { type: 'number', ...(spec.min !== undefined ? { minimum: spec.min } : {}), ...(spec.max !== undefined ? { maximum: spec.max } : {}) };
      case 'string-or-number':
        return { type: ['string', 'number'] };
      case 'boolean':
        return { type: 'boolean' };
      case 'const':
        return { const: spec.value };
      case 'enum':
        return { enum: [...spec.values] };
      case 'href':
        return { type: 'string', minLength: 1, maxLength: 2048 };
      case 'object':
        return { $ref: `#/$defs/${spec.ref}` };
      case 'array':
        return { type: 'array', items: field(spec.items), ...(spec.maxItems !== undefined ? { maxItems: spec.maxItems } : {}) };
      default:
        throw new Error(`Unknown field kind ${spec.kind}`);
    }
  };
  const object = (spec, extraRequired = {}, extraProps = {}) => {
    const required = { ...extraRequired, ...spec.required };
    const properties = {};
    for (const [k, v] of Object.entries(extraProps)) properties[k] = v;
    for (const [k, v] of Object.entries(required)) properties[k] ??= field(v);
    for (const [k, v] of Object.entries(spec.optional)) properties[k] = field(v);
    return {
      type: 'object',
      ...(spec.description ? { description: spec.description } : {}),
      required: [...new Set([...Object.keys(extraProps), ...Object.keys(required)])],
      properties,
      // Unknown fields are allowed (forward compatibility) and preserved by renderJson.
      additionalProperties: true,
    };
  };
  const defs = {
    Id: {
      type: 'string',
      description: 'A stable domain id. Presentation labels (C-01, F-01, E-01) are assigned by renderers and rejected here.',
      pattern: ID_PATTERN,
      not: { pattern: PRESENTATION_LABEL_PATTERN },
    },
    Timestamp: {
      type: 'string',
      format: 'date-time',
      description: 'ISO 8601 date-time with an explicit zone; the same pattern validateEvent uses.',
      pattern: TIMESTAMP_PATTERN,
    },
  };
  for (const [name, spec] of Object.entries(OBJECT_SPEC)) defs[name] = object(spec);
  for (const type of EVENT_TYPES) {
    const defName = `Event_${type}`;
    defs[defName] = object(EVENT_SPEC[type], EVENT_BASE_SPEC, { type: { const: type } });
  }
  const schema = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://frame12.dev/schema/terminal/events.v1.json',
    title: '@frame12/terminal event contract',
    description: `Event contract v${SCHEMA_VERSION}. One JSON object per NDJSON line. Events larger than 8 KiB (snapshots: 1 MiB) are rejected; unknown event types are ignored with a warning; unknown fields are preserved. Generated from src/core/contract.ts — do not edit by hand.`,
    oneOf: EVENT_TYPES.map((t) => ({ $ref: `#/$defs/Event_${t}` })),
    $defs: defs,
  };
  return `${JSON.stringify(schema, null, 2)}\n`;
}

function compile(outDir) {
  execFileSync(process.execPath, [tsc, '-p', path.join(PKG_ROOT, 'tsconfig.json'), '--outDir', outDir], { stdio: 'inherit' });
}

const tokensModule = await renderTokensModule();

if (check) {
  const drift = [];
  if (!fs.existsSync(TOKENS_GENERATED) || fs.readFileSync(TOKENS_GENERATED, 'utf8') !== tokensModule) {
    drift.push('src/core/tokens.generated.ts');
  }
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'f12-terminal-check-'));
  try {
    compile(tmp);
    for (const f of listFiles(tmp)) {
      const onDisk = path.join(PKG_ROOT, 'dist', f);
      if (!fs.existsSync(onDisk) || fs.readFileSync(onDisk, 'utf8') !== fs.readFileSync(path.join(tmp, f), 'utf8')) drift.push(`dist/${f}`);
    }
    const expected = new Set([...listFiles(tmp), 'events.schema.json']);
    for (const f of listFiles(path.join(PKG_ROOT, 'dist'))) if (!expected.has(f)) drift.push(`dist/${f} (unexpected)`);
    const schema = await renderSchema(tmp);
    if (!fs.existsSync(SCHEMA_PATH) || fs.readFileSync(SCHEMA_PATH, 'utf8') !== schema) drift.push('schema/events.schema.json');
    const distSchema = path.join(PKG_ROOT, 'dist/events.schema.json');
    if (!fs.existsSync(distSchema) || fs.readFileSync(distSchema, 'utf8') !== schema) drift.push('dist/events.schema.json');
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  if (drift.length) {
    console.error(`@frame12/terminal generated files are stale: ${drift.join(', ')}. Run: npm run build --workspace=@frame12/terminal`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(TOKENS_GENERATED, tokensModule);
  const dist = path.join(PKG_ROOT, 'dist');
  fs.rmSync(dist, { recursive: true, force: true });
  compile(dist);
  // The `frame12-term` bin (npm also sets this on install; keep the committed file runnable).
  fs.chmodSync(path.join(dist, 'cli/bin.js'), 0o755);
  fs.mkdirSync(path.dirname(SCHEMA_PATH), { recursive: true });
  const schema = await renderSchema(dist);
  fs.writeFileSync(SCHEMA_PATH, schema);
  // The published copy: package.json exports it as `@frame12/terminal/schema.json`.
  fs.writeFileSync(path.join(dist, 'events.schema.json'), schema);
  console.log('Built @frame12/terminal dist/ and schema/events.schema.json.');
}
