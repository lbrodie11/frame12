#!/usr/bin/env node
/**
 * Generates src/core/east-asian-width.generated.ts from the Unicode Character Database's
 * EastAsianWidth.txt (UAX #11). The data file is NOT fetched at build time: download it once,
 * then pass its path. The generated table is committed, so builds stay offline and deterministic.
 *
 *   curl -sSfO https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt
 *   node scripts/gen-unicode-width.mjs EastAsianWidth.txt
 *
 * Only W (wide), F (fullwidth) and A (ambiguous) ranges are kept; everything else is narrow.
 * Adjacent ranges with the same class are merged.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-unicode-width.mjs <EastAsianWidth.txt>');
  process.exit(2);
}
const text = fs.readFileSync(src, 'utf8');
const version = /EastAsianWidth-(\d+\.\d+\.\d+)\.txt/.exec(text)?.[1];
if (!version) throw new Error('Could not read the UCD version from the file header.');

const wide = [];
const ambiguous = [];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);
  if (!m) continue;
  const lo = parseInt(m[1], 16);
  const hi = m[2] ? parseInt(m[2], 16) : lo;
  const cls = m[3];
  if (cls === 'W' || cls === 'F') wide.push([lo, hi]);
  else if (cls === 'A') ambiguous.push([lo, hi]);
}
const merge = (ranges) => {
  ranges.sort((a, b) => a[0] - b[0]);
  const out = [];
  for (const r of ranges) {
    const last = out[out.length - 1];
    if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1]);
    else out.push([...r]);
  }
  return out;
};
// Flat [lo0, hi0, lo1, hi1, ...] arrays keep the generated file small and binary-searchable.
const flat = (ranges) =>
  merge(ranges)
    .flat()
    .map((n) => '0x' + n.toString(16))
    .reduce((acc, v, i) => acc + (i % 12 === 0 ? '\n  ' : ' ') + v + ',', '');

const out = `/* Generated by scripts/gen-unicode-width.mjs from EastAsianWidth-${version}.txt — do not edit by hand. */
/** Unicode version of the UAX #11 data below. */
export const EAST_ASIAN_WIDTH_UNICODE_VERSION = '${version}';

/** Sorted, merged, inclusive [lo, hi] pairs of code points with East_Asian_Width W or F. */
export const WIDE_RANGES: readonly number[] = [${flat(wide)}
];

/** Sorted, merged, inclusive [lo, hi] pairs of code points with East_Asian_Width A (ambiguous). */
export const AMBIGUOUS_RANGES: readonly number[] = [${flat(ambiguous)}
];
`;
const dest = path.join(__dirname, '..', 'src', 'core', 'east-asian-width.generated.ts');
fs.writeFileSync(dest, out);
console.log(`Wrote ${path.relative(process.cwd(), dest)} (Unicode ${version}: ${merge(wide).length} wide, ${merge(ambiguous).length} ambiguous ranges).`);
