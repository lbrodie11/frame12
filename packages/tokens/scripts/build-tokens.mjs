#!/usr/bin/env node
/**
 * Deterministically builds @frame12/tokens artifacts from src/tokens.source.json:
 *   - dist/tokens.css
 *   - dist/tokens.json (resolved W3C DTCG 2025.10 JSON)
 *   - dist/index.js
 *   - dist/index.d.ts
 *   - registry/styles/frame12-tokens.css
 *   - registry/styles/frame12.css (between /* @tokens:start *\/ and /* @tokens:end *\/)
 *
 * Options:
 *   --check            Verify that all generated outputs and the registry CSS region
 *                      match the source without modifying files on disk.
 *   --out-dir <dir>    Write dist/{tokens.css,tokens.json,index.js,index.d.ts} to <dir>
 *                      without modifying repository files (used by determinism tests).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(PKG_ROOT, '../..');
const SOURCE_PATH = path.join(PKG_ROOT, 'src/tokens.source.json');
const DIST_DIR = path.join(PKG_ROOT, 'dist');
const REGISTRY_CSS_PATH = path.join(REPO_ROOT, 'registry/styles/frame12.css');
const REGISTRY_TOKENS_CSS_PATH = path.join(REPO_ROOT, 'registry/styles/frame12-tokens.css');

const START_MARKER = '/* @tokens:start */';
const END_MARKER = '/* @tokens:end */';
const GENERATED_HEADER = '/* Generated by @frame12/tokens — generated, do not edit by hand. */';

const GENERIC_FONT_FAMILIES = new Set([
  'serif',
  'sans-serif',
  'monospace',
  'cursive',
  'fantasy',
  'system-ui',
  'ui-serif',
  'ui-sans-serif',
  'ui-monospace',
  'ui-rounded',
  'emoji',
  'math',
  'fangsong',
  '-apple-system',
  'BlinkMacSystemFont',
]);

export function componentsToHex(components) {
  if (
    !Array.isArray(components) ||
    components.length !== 3 ||
    !components.every((c) => typeof c === 'number' && Number.isFinite(c) && c >= 0 && c <= 1)
  ) {
    throw new Error(`Invalid DTCG sRGB components: ${JSON.stringify(components)}`);
  }
  const [r, g, b] = components.map((c) => Math.round(c * 255));
  return (
    '#' +
    [r, g, b]
      .map((n) => n.toString(16).padStart(2, '0'))
      .join('')
      .toLowerCase()
  );
}

export function formatDtcgColorCss(colorVal, label = 'color') {
  const alpha = colorVal.alpha ?? 1;
  const computedHex = componentsToHex(colorVal.components);
  if (colorVal.hex !== undefined) {
    if (alpha !== 1) {
      throw new Error(
        `${label}: color.hex ("${colorVal.hex}") must be omitted when alpha < 1 (got alpha=${alpha})`,
      );
    }
    if (typeof colorVal.hex !== 'string' || colorVal.hex.toLowerCase() !== computedHex) {
      throw new Error(
        `${label}: color.hex ("${colorVal.hex}") does not match rounded sRGB components (${computedHex})`,
      );
    }
  }
  if (alpha === 1) {
    return computedHex;
  }
  const [r, g, b] = colorVal.components.map((c) => Math.round(c * 255));
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

export function formatDtcgDimensionCss(dimVal, { zeroUnitless = false } = {}) {
  if (zeroUnitless && dimVal.value === 0) {
    return '0';
  }
  return `${dimVal.value}${dimVal.unit}`;
}

export function formatDtcgDurationCss(durVal) {
  return `${durVal.value}${durVal.unit}`;
}

export function formatDtcgFontFamilyCss(fontVal) {
  const list = Array.isArray(fontVal) ? fontVal : [fontVal];
  return list
    .map((family) => {
      const trimmed = family.trim();
      if (/^var\(/.test(trimmed) || GENERIC_FONT_FAMILIES.has(trimmed)) {
        return trimmed;
      }
      const unquoted =
        trimmed.startsWith('"') && trimmed.endsWith('"')
          ? trimmed.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, '\\')
          : trimmed;
      return `"${unquoted.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
    })
    .join(', ');
}

export function formatFontFallbackCss(fb) {
  const srcList = fb.local.map((name) => `local(${JSON.stringify(name)})`).join(', ');
  return [
    '@font-face {',
    `  font-family: ${JSON.stringify(fb.fontFamily)};`,
    `  src: ${srcList};`,
    `  font-weight: ${fb.fontWeight};`,
    `  size-adjust: ${fb.sizeAdjust};`,
    `  ascent-override: ${fb.ascentOverride};`,
    `  descent-override: ${fb.descentOverride};`,
    `  line-gap-override: ${fb.lineGapOverride};`,
    '}',
  ].join('\n');
}

function formatShadowLayerCss(layer, label = 'shadow') {
  const parts = [];
  if (layer.inset) {
    parts.push('inset');
  }
  parts.push(formatDtcgDimensionCss(layer.offsetX, { zeroUnitless: true }));
  parts.push(formatDtcgDimensionCss(layer.offsetY, { zeroUnitless: true }));
  parts.push(formatDtcgDimensionCss(layer.blur, { zeroUnitless: true }));
  if (layer.spread && layer.spread.value !== 0) {
    parts.push(formatDtcgDimensionCss(layer.spread, { zeroUnitless: true }));
  }
  parts.push(formatDtcgColorCss(layer.color, `${label}.color`));
  return parts.join(' ');
}

export function formatDtcgShadowCss(shadowVal, label = 'shadow') {
  const layers = Array.isArray(shadowVal) ? shadowVal : [shadowVal];
  return layers.map((layer, idx) => formatShadowLayerCss(layer, `${label}[${idx}]`)).join(', ');
}

function getColorForMode(token, mode) {
  const modes = token?.$extensions?.['dev.frame12.modes'];
  if (modes && modes[mode]) {
    return modes[mode];
  }
  return token.$value;
}

export function buildTokenArtifacts(source = JSON.parse(fs.readFileSync(SOURCE_PATH, 'utf8'))) {
  const colorEntries = Object.entries(source.color).filter(([k]) => !k.startsWith('$'));
  for (const [name, token] of colorEntries) {
    formatDtcgColorCss(token.$value, `color.${name}.$value`);
    const modes = token?.$extensions?.['dev.frame12.modes'];
    if (modes?.light) {
      formatDtcgColorCss(modes.light, `color.${name}.modes.light`);
      if (JSON.stringify(token.$value) !== JSON.stringify(modes.light)) {
        throw new Error(
          `color.${name}.$value diverges from $extensions["dev.frame12.modes"].light`,
        );
      }
    }
    if (modes?.dark) {
      formatDtcgColorCss(modes.dark, `color.${name}.modes.dark`);
    }
  }

  const themedColorEntries = colorEntries.filter(
    ([, v]) => v?.$extensions?.['dev.frame12.scope'] !== 'root',
  );
  const rootColorEntries = colorEntries.filter(
    ([, v]) => v?.$extensions?.['dev.frame12.scope'] === 'root',
  );
  const fontEntries = Object.entries(source.font).filter(([k]) => !k.startsWith('$'));
  const fontFallbacks = source.font?.$extensions?.['dev.frame12.fallbacks'] || [];
  const gutterEntries = Object.entries(source.gutter).filter(([k]) => !k.startsWith('$'));
  const shadowEntries = Object.entries(source.shadow).filter(([k]) => !k.startsWith('$'));

  // 1. Build dist/tokens.css
  const fallbackLines =
    fontFallbacks.length > 0
      ? [
          '/* Cross-platform metric-matched fallbacks for Dela Gothic One, Zen Kaku Gothic New, and',
          '   M PLUS 1 Code across macOS, Windows, Linux (Liberation/DejaVu/Noto), and Android (Roboto)',
          '   so cold-network .woff2 swaps do not reflow headings, controls, paragraphs, or tables. */',
          fontFallbacks.map(formatFontFallbackCss).join('\n\n'),
          '',
        ]
      : [];

  const rootLines = [
    GENERATED_HEADER,
    ...fallbackLines,
    ':where(:root) {',
    ...fontEntries.map(
      ([name, token]) => `  --font-f-${name}: ${formatDtcgFontFamilyCss(token.$value)};`,
    ),
    '',
    ...gutterEntries.map(
      ([name, token]) => `  --f-gutter-${name}: ${formatDtcgDimensionCss(token.$value)};`,
    ),
    '',
    `  --f-stroke: ${formatDtcgDimensionCss(source.stroke.ink.$value)};`,
    `  --f-stroke-pencil: ${formatDtcgDimensionCss(source.stroke.pencil.$value)};`,
    `  --f-stroke-detail: ${formatDtcgDimensionCss(source.stroke.detail.$value)};`,
    `  --f-pose: ${formatDtcgDurationCss(source.motion.pose.$value)};`,
    `  --f-fps: ${source.motion.fps.$value};`,
    '',
    ...shadowEntries.map(
      ([name, token]) =>
        `  --f-shadow-${name}: ${formatDtcgShadowCss(token.$value, `shadow.${name}`)};`,
    ),
    ...rootColorEntries.map(
      ([name, token]) =>
        `  --f-${name}: ${formatDtcgColorCss(getColorForMode(token, 'light'), `color.${name}.light`)};`,
    ),
    '}',
    '',
    ':where(:root),',
    ':root[data-theme="light"],',
    '.f12-theme-light {',
    ...themedColorEntries.map(
      ([name, token]) =>
        `  --f-${name}: ${formatDtcgColorCss(getColorForMode(token, 'light'), `color.${name}.light`)};`,
    ),
    '  color-scheme: light;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]):not(.f12-theme-light) {',
    ...themedColorEntries.map(
      ([name, token]) =>
        `    --f-${name}: ${formatDtcgColorCss(getColorForMode(token, 'dark'), `color.${name}.dark`)};`,
    ),
    '    color-scheme: dark;',
    '  }',
    '}',
    '',
    ':root[data-theme="dark"],',
    '.f12-theme-dark {',
    ...themedColorEntries.map(
      ([name, token]) =>
        `  --f-${name}: ${formatDtcgColorCss(getColorForMode(token, 'dark'), `color.${name}.dark`)};`,
    ),
    '  color-scheme: dark;',
    '}',
    '',
  ];
  const tokensCss = rootLines.join('\n');

  // 2. Build dist/tokens.json (resolved W3C DTCG 2025.10 JSON; color $value derived from modes.light)
  const resolvedJsonObj = {
    $description: source.$description,
    $extensions: {
      ...(source.$extensions || {}),
      'dev.frame12.generated': 'Generated by @frame12/tokens — generated, do not edit by hand.',
    },
    color: {
      $type: 'color',
      ...Object.fromEntries(
        colorEntries.map(([name, token]) => [
          name,
          {
            $type: 'color',
            $value: structuredClone(getColorForMode(token, 'light')),
            $description: token.$description,
            $extensions: {
              ...(token.$extensions || {}),
              'dev.frame12.cssVar': `--f-${name}`,
            },
          },
        ]),
      ),
    },
    font: {
      $type: 'fontFamily',
      ...(source.font.$extensions ? { $extensions: source.font.$extensions } : {}),
      ...Object.fromEntries(
        fontEntries.map(([name, token]) => [
          name,
          {
            $type: 'fontFamily',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--font-f-${name}`,
            },
          },
        ]),
      ),
    },
    gutter: {
      $type: 'dimension',
      ...Object.fromEntries(
        gutterEntries.map(([name, token]) => [
          name,
          {
            $type: 'dimension',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--f-gutter-${name}`,
            },
          },
        ]),
      ),
    },
    stroke: {
      $type: 'dimension',
      ink: {
        $type: 'dimension',
        $value: source.stroke.ink.$value,
        $description: source.stroke.ink.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-stroke',
        },
      },
      ...Object.fromEntries(
        ['pencil', 'detail'].map((name) => [
          name,
          {
            $type: 'dimension',
            $value: source.stroke[name].$value,
            $description: source.stroke[name].$description,
            $extensions: {
              'dev.frame12.cssVar': `--f-stroke-${name}`,
            },
          },
        ]),
      ),
    },
    motion: {
      pose: {
        $type: 'duration',
        $value: source.motion.pose.$value,
        $description: source.motion.pose.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-pose',
        },
      },
      fps: {
        $type: 'number',
        $value: source.motion.fps.$value,
        $description: source.motion.fps.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-fps',
        },
      },
    },
    shadow: {
      $type: 'shadow',
      ...Object.fromEntries(
        shadowEntries.map(([name, token]) => [
          name,
          {
            $type: 'shadow',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--f-shadow-${name}`,
            },
          },
        ]),
      ),
    },
  };
  const tokensJson = JSON.stringify(resolvedJsonObj, null, 2) + '\n';

  // 3. Build dist/index.js and dist/index.d.ts
  function buildModeObject(mode) {
    const out = {};
    for (const [name, token] of colorEntries) {
      out[name] = formatDtcgColorCss(getColorForMode(token, mode), `color.${name}.${mode}`);
    }
    return out;
  }

  const tsTokensObj = {
    light: buildModeObject('light'),
    dark: buildModeObject('dark'),
    gutters: Object.fromEntries(
      gutterEntries.map(([k, v]) => [k, formatDtcgDimensionCss(v.$value)]),
    ),
    stroke: {
      ink: formatDtcgDimensionCss(source.stroke.ink.$value),
      pencil: formatDtcgDimensionCss(source.stroke.pencil.$value),
      detail: formatDtcgDimensionCss(source.stroke.detail.$value),
    },
    motion: {
      pose: formatDtcgDurationCss(source.motion.pose.$value),
      fps: source.motion.fps.$value,
    },
    fonts: Object.fromEntries(
      fontEntries.map(([k, v]) => [k, formatDtcgFontFamilyCss(v.$value)]),
    ),
    shadow: Object.fromEntries(
      shadowEntries.map(([k, v]) => [k, formatDtcgShadowCss(v.$value, `shadow.${k}`)]),
    ),
  };

  const indexJs = [
    GENERATED_HEADER,
    'const deepFreeze = (obj) => {',
    '  Object.freeze(obj);',
    '  for (const val of Object.values(obj)) {',
    '    if (val && typeof val === "object" && !Object.isFrozen(val)) {',
    '      deepFreeze(val);',
    '    }',
    '  }',
    '  return obj;',
    '};',
    '',
    `export const tokens = deepFreeze(${JSON.stringify(tsTokensObj, null, 2)});`,
    '',
    'export const { light, dark, gutters, stroke, motion, fonts, shadow } = tokens;',
    '',
    `export const cssText = ${JSON.stringify(tokensCss)};`,
    '',
    'export default tokens;',
    '',
  ].join('\n');

  function formatDtsFields(obj, indent = 2) {
    const pad = ' '.repeat(indent);
    const lines = [];
    for (const [k, v] of Object.entries(obj)) {
      const keyStr = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
      const valType = typeof v === 'number' ? 'number' : 'string';
      lines.push(`${pad}readonly ${keyStr}: ${valType};`);
    }
    return lines.join('\n');
  }

  const indexDts = [
    GENERATED_HEADER,
    "export type Frame12ThemeMode = 'light' | 'dark';",
    '',
    'export interface Frame12Palette {',
    formatDtsFields(tsTokensObj.light, 2),
    '}',
    '',
    'export interface Frame12Gutters {',
    formatDtsFields(tsTokensObj.gutters, 2),
    '}',
    '',
    'export interface Frame12Stroke {',
    formatDtsFields(tsTokensObj.stroke, 2),
    '}',
    '',
    'export interface Frame12Motion {',
    formatDtsFields(tsTokensObj.motion, 2),
    '}',
    '',
    'export interface Frame12Fonts {',
    formatDtsFields(tsTokensObj.fonts, 2),
    '}',
    '',
    'export interface Frame12Shadow {',
    formatDtsFields(tsTokensObj.shadow, 2),
    '}',
    '',
    'export interface Frame12Tokens {',
    '  readonly light: Frame12Palette;',
    '  readonly dark: Frame12Palette;',
    '  readonly gutters: Frame12Gutters;',
    '  readonly stroke: Frame12Stroke;',
    '  readonly motion: Frame12Motion;',
    '  readonly fonts: Frame12Fonts;',
    '  readonly shadow: Frame12Shadow;',
    '}',
    '',
    'export declare const tokens: Frame12Tokens;',
    'export declare const light: Frame12Palette;',
    'export declare const dark: Frame12Palette;',
    'export declare const gutters: Frame12Gutters;',
    'export declare const stroke: Frame12Stroke;',
    'export declare const motion: Frame12Motion;',
    'export declare const fonts: Frame12Fonts;',
    'export declare const shadow: Frame12Shadow;',
    'export declare const cssText: string;',
    '',
    'export default tokens;',
    '',
  ].join('\n');

  return {
    tokensCss,
    tokensJson,
    indexJs,
    indexDts,
  };
}

export function extractRegistryTokenRegion(registryCss) {
  const startIdx = registryCss.indexOf(START_MARKER);
  const endIdx = registryCss.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    return null;
  }
  const innerStart = startIdx + START_MARKER.length;
  const inner = registryCss.slice(innerStart, endIdx);
  return inner.replace(/\r\n/g, '\n').replace(/^\n/, '');
}

export function replaceRegistryTokenRegion(registryCss, tokensCss) {
  const startIdx = registryCss.indexOf(START_MARKER);
  const endIdx = registryCss.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    throw new Error(
      `Missing ${START_MARKER} / ${END_MARKER} markers in ${path.relative(REPO_ROOT, REGISTRY_CSS_PATH)}`,
    );
  }
  const eol = registryCss.includes('\r\n') ? '\r\n' : '\n';
  const normalizedTokens = tokensCss.replace(/\r?\n/g, eol);
  const before = registryCss.slice(0, startIdx + START_MARKER.length);
  const after = registryCss.slice(endIdx);
  return `${before}${eol}${normalizedTokens}${after}`;
}

export function checkTokenSync({
  distDir = DIST_DIR,
  registryCssPath = REGISTRY_CSS_PATH,
  registryTokensCssPath = REGISTRY_TOKENS_CSS_PATH,
} = {}) {
  const { tokensCss, tokensJson, indexJs, indexDts } = buildTokenArtifacts();
  const drifts = [];

  const expectedFiles = [
    { filePath: path.join(distDir, 'tokens.css'), expected: tokensCss },
    { filePath: path.join(distDir, 'tokens.json'), expected: tokensJson },
    { filePath: path.join(distDir, 'index.js'), expected: indexJs },
    { filePath: path.join(distDir, 'index.d.ts'), expected: indexDts },
    { filePath: registryTokensCssPath, expected: tokensCss },
  ];

  for (const { filePath, expected } of expectedFiles) {
    const rel = path.relative(REPO_ROOT, filePath);
    if (!fs.existsSync(filePath)) {
      drifts.push(`Missing generated token artifact: ${rel}`);
    } else if (fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      drifts.push(`Token artifact drift in ${rel}`);
    }
  }

  if (!fs.existsSync(registryCssPath)) {
    drifts.push(`Missing registry stylesheet: ${path.relative(REPO_ROOT, registryCssPath)}`);
  } else {
    const regCss = fs.readFileSync(registryCssPath, 'utf8');
    const region = extractRegistryTokenRegion(regCss);
    if (region === null) {
      drifts.push(
        `Missing ${START_MARKER} / ${END_MARKER} markers in ${path.relative(REPO_ROOT, registryCssPath)}`,
      );
    } else if (region !== tokensCss) {
      drifts.push(
        `Token region drift between packages/tokens/src/tokens.source.json and ${path.relative(REPO_ROOT, registryCssPath)}`,
      );
    }
  }

  return drifts;
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const drifts = checkTokenSync();
    if (drifts.length > 0) {
      console.error('FRAME/12 token synchronization check failed:');
      for (const d of drifts) {
        console.error(`  - ${d}`);
      }
      process.exit(1);
    }
    console.log('FRAME/12 token synchronization check passed.');
    process.exit(0);
  }

  const outDirIdx = process.argv.indexOf('--out-dir');
  const customOutDir = outDirIdx !== -1 ? process.argv[outDirIdx + 1] : null;
  const targetDistDir = customOutDir ? path.resolve(customOutDir) : DIST_DIR;

  const { tokensCss, tokensJson, indexJs, indexDts } = buildTokenArtifacts();
  fs.mkdirSync(targetDistDir, { recursive: true });
  fs.writeFileSync(path.join(targetDistDir, 'tokens.css'), tokensCss);
  fs.writeFileSync(path.join(targetDistDir, 'tokens.json'), tokensJson);
  fs.writeFileSync(path.join(targetDistDir, 'index.js'), indexJs);
  fs.writeFileSync(path.join(targetDistDir, 'index.d.ts'), indexDts);

  if (!customOutDir) {
    fs.writeFileSync(REGISTRY_TOKENS_CSS_PATH, tokensCss);
    if (fs.existsSync(REGISTRY_CSS_PATH)) {
      const regCss = fs.readFileSync(REGISTRY_CSS_PATH, 'utf8');
      const updated = replaceRegistryTokenRegion(regCss, tokensCss);
      fs.writeFileSync(REGISTRY_CSS_PATH, updated);
    }
    console.log(
      'Built @frame12/tokens: dist/{tokens.css,tokens.json,index.js,index.d.ts}, registry/styles/frame12-tokens.css, and registry/styles/frame12.css token block.',
    );
  } else {
    console.log(`Built @frame12/tokens dist artifacts into ${targetDistDir}.`);
  }
}
