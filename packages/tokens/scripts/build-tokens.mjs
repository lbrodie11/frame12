#!/usr/bin/env node
/**
 * Deterministically builds @frame12/tokens artifacts from src/tokens.source.json:
 *   - dist/tokens.css
 *   - dist/tokens.json (resolved W3C DTCG JSON)
 *   - dist/index.js
 *   - dist/index.d.ts
 *   - registry/styles/frame12-tokens.css
 *   - registry/styles/frame12.css (between /* @tokens:start *\/ and /* @tokens:end *\/)
 *
 * Pass `--check` to verify that all generated outputs and the registry CSS region
 * match the source without modifying files on disk.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(PKG_ROOT, '../..');
const SOURCE_PATH = path.join(PKG_ROOT, 'src/tokens.source.json');
const DIST_DIR = path.join(PKG_ROOT, 'dist');
const REGISTRY_CSS_PATH = path.join(REPO_ROOT, 'registry/styles/frame12.css');
const REGISTRY_TOKENS_CSS_PATH = path.join(REPO_ROOT, 'registry/styles/frame12-tokens.css');

const START_MARKER = '/* @tokens:start */';
const END_MARKER = '/* @tokens:end */';
const GENERATED_HEADER = '/* Generated by @frame12/tokens — generated, do not edit by hand. */';

export function buildTokenArtifacts(source = JSON.parse(fs.readFileSync(SOURCE_PATH, 'utf8'))) {
  const colorEntries = Object.entries(source.color).filter(([k]) => !k.startsWith('$'));
  const themedColorEntries = colorEntries.filter(
    ([, v]) => v?.$extensions?.['dev.frame12.scope'] !== 'root',
  );
  const rootColorEntries = colorEntries.filter(
    ([, v]) => v?.$extensions?.['dev.frame12.scope'] === 'root',
  );
  const fontEntries = Object.entries(source.font).filter(([k]) => !k.startsWith('$'));
  const gutterEntries = Object.entries(source.gutter).filter(([k]) => !k.startsWith('$'));
  const shadowEntries = Object.entries(source.shadow).filter(([k]) => !k.startsWith('$'));

  // 1. Build dist/tokens.css
  const rootLines = [
    GENERATED_HEADER,
    ':where(:root) {',
    ...fontEntries.map(([name, token]) => `  --font-f-${name}: ${token.$value};`),
    '',
    ...gutterEntries.map(([name, token]) => `  --f-gutter-${name}: ${token.$value};`),
    '',
    `  --f-stroke: ${source.stroke.ink.$value};`,
    `  --f-pose: ${source.motion.pose.$value};`,
    `  --f-fps: ${source.motion.fps.$value};`,
    '',
    ...shadowEntries.map(([name, token]) => `  --f-shadow-${name}: ${token.$value};`),
    ...rootColorEntries.map(([name, token]) => `  --f-${name}: ${token.$value.light};`),
    '}',
    '',
    ':where(:root),',
    ':root[data-theme="light"],',
    '.f12-theme-light {',
    ...themedColorEntries.map(([name, token]) => `  --f-${name}: ${token.$value.light};`),
    '  color-scheme: light;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]):not(.f12-theme-light) {',
    ...themedColorEntries.map(([name, token]) => `    --f-${name}: ${token.$value.dark};`),
    '    color-scheme: dark;',
    '  }',
    '}',
    '',
    ':root[data-theme="dark"],',
    '.f12-theme-dark {',
    ...themedColorEntries.map(([name, token]) => `  --f-${name}: ${token.$value.dark};`),
    '  color-scheme: dark;',
    '}',
    '',
  ];
  const tokensCss = rootLines.join('\n');

  // 2. Build dist/tokens.json (resolved W3C DTCG JSON)
  const resolvedJsonObj = {
    $schema: source.$schema,
    $comment: 'Generated by @frame12/tokens — generated, do not edit by hand.',
    $description: source.$description,
    color: {
      $type: 'color',
      ...Object.fromEntries(
        colorEntries.map(([name, token]) => [
          name,
          {
            $type: 'color',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              ...(token.$extensions || {}),
              'dev.frame12.cssVar': `--f-${name}`,
            },
          },
        ]),
      ),
    },
    font: {
      $type: 'fontFamily',
      ...Object.fromEntries(
        fontEntries.map(([name, token]) => [
          name,
          {
            $type: 'fontFamily',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--font-f-${name}`,
            },
          },
        ]),
      ),
    },
    gutter: {
      $type: 'dimension',
      ...Object.fromEntries(
        gutterEntries.map(([name, token]) => [
          name,
          {
            $type: 'dimension',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--f-gutter-${name}`,
            },
          },
        ]),
      ),
    },
    stroke: {
      $type: 'dimension',
      ink: {
        $type: 'dimension',
        $value: source.stroke.ink.$value,
        $description: source.stroke.ink.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-stroke',
        },
      },
    },
    motion: {
      pose: {
        $type: 'duration',
        $value: source.motion.pose.$value,
        $description: source.motion.pose.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-pose',
        },
      },
      fps: {
        $type: 'number',
        $value: source.motion.fps.$value,
        $description: source.motion.fps.$description,
        $extensions: {
          'dev.frame12.cssVar': '--f-fps',
        },
      },
    },
    shadow: {
      $type: 'shadow',
      ...Object.fromEntries(
        shadowEntries.map(([name, token]) => [
          name,
          {
            $type: 'shadow',
            $value: token.$value,
            $description: token.$description,
            $extensions: {
              'dev.frame12.cssVar': `--f-shadow-${name}`,
            },
          },
        ]),
      ),
    },
  };
  const tokensJson = JSON.stringify(resolvedJsonObj, null, 2) + '\n';

  // 3. Build dist/index.js and dist/index.d.ts
  const toCamel = (s) => s.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());

  function buildModeObject(mode) {
    const out = {};
    for (const [name, token] of colorEntries) {
      out[name] = token.$value[mode];
      const camel = toCamel(name);
      if (camel !== name) {
        out[camel] = token.$value[mode];
      }
    }
    return out;
  }

  const tsTokensObj = {
    light: buildModeObject('light'),
    dark: buildModeObject('dark'),
    gutters: Object.fromEntries(gutterEntries.map(([k, v]) => [k, v.$value])),
    stroke: {
      ink: source.stroke.ink.$value,
    },
    motion: {
      pose: source.motion.pose.$value,
      fps: source.motion.fps.$value,
    },
    fonts: Object.fromEntries(fontEntries.map(([k, v]) => [k, v.$value])),
    shadow: Object.fromEntries(shadowEntries.map(([k, v]) => [k, v.$value])),
  };

  const indexJs = [
    GENERATED_HEADER,
    'const deepFreeze = (obj) => {',
    '  Object.freeze(obj);',
    '  for (const val of Object.values(obj)) {',
    '    if (val && typeof val === "object" && !Object.isFrozen(val)) {',
    '      deepFreeze(val);',
    '    }',
    '  }',
    '  return obj;',
    '};',
    '',
    `export const tokens = deepFreeze(${JSON.stringify(tsTokensObj, null, 2)});`,
    '',
    'export const { light, dark, gutters, stroke, motion, fonts, shadow } = tokens;',
    '',
    `export const cssText = ${JSON.stringify(tokensCss)};`,
    '',
    'export default tokens;',
    '',
  ].join('\n');

  function formatDtsObject(obj, indent = 2) {
    const pad = ' '.repeat(indent);
    const lines = [];
    for (const [k, v] of Object.entries(obj)) {
      const keyStr = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
      if (v && typeof v === 'object') {
        lines.push(`${pad}readonly ${keyStr}: {`);
        lines.push(formatDtsObject(v, indent + 2));
        lines.push(`${pad}};`);
      } else {
        lines.push(`${pad}readonly ${keyStr}: ${JSON.stringify(v)};`);
      }
    }
    return lines.join('\n');
  }

  const indexDts = [
    GENERATED_HEADER,
    'export declare const tokens: {',
    formatDtsObject(tsTokensObj, 2),
    '};',
    '',
    'export type Frame12Tokens = typeof tokens;',
    "export type Frame12ThemeMode = 'light' | 'dark';",
    '',
    'export declare const light: Frame12Tokens["light"];',
    'export declare const dark: Frame12Tokens["dark"];',
    'export declare const gutters: Frame12Tokens["gutters"];',
    'export declare const stroke: Frame12Tokens["stroke"];',
    'export declare const motion: Frame12Tokens["motion"];',
    'export declare const fonts: Frame12Tokens["fonts"];',
    'export declare const shadow: Frame12Tokens["shadow"];',
    'export declare const cssText: string;',
    '',
    'export default tokens;',
    '',
  ].join('\n');

  return {
    tokensCss,
    tokensJson,
    indexJs,
    indexDts,
  };
}

export function extractRegistryTokenRegion(registryCss) {
  const startIdx = registryCss.indexOf(START_MARKER);
  const endIdx = registryCss.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    return null;
  }
  const innerStart = startIdx + START_MARKER.length;
  const inner = registryCss.slice(innerStart, endIdx);
  return inner.replace(/\r\n/g, '\n').replace(/^\n/, '');
}

export function replaceRegistryTokenRegion(registryCss, tokensCss) {
  const startIdx = registryCss.indexOf(START_MARKER);
  const endIdx = registryCss.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    throw new Error(
      `Missing ${START_MARKER} / ${END_MARKER} markers in ${ path.relative(REPO_ROOT, REGISTRY_CSS_PATH) }`,
    );
  }
  const before = registryCss.slice(0, startIdx + START_MARKER.length);
  const after = registryCss.slice(endIdx);
  return `${before}\n${tokensCss}${after}`;
}

export function checkTokenSync() {
  const { tokensCss, tokensJson, indexJs, indexDts } = buildTokenArtifacts();
  const drifts = [];

  const expectedFiles = [
    { filePath: path.join(DIST_DIR, 'tokens.css'), expected: tokensCss },
    { filePath: path.join(DIST_DIR, 'tokens.json'), expected: tokensJson },
    { filePath: path.join(DIST_DIR, 'index.js'), expected: indexJs },
    { filePath: path.join(DIST_DIR, 'index.d.ts'), expected: indexDts },
    { filePath: REGISTRY_TOKENS_CSS_PATH, expected: tokensCss },
  ];

  for (const { filePath, expected } of expectedFiles) {
    const rel = path.relative(REPO_ROOT, filePath);
    if (!fs.existsSync(filePath)) {
      drifts.push(`Missing generated token artifact: ${rel}`);
    } else if (fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      drifts.push(`Token artifact drift in ${rel}`);
    }
  }

  if (!fs.existsSync(REGISTRY_CSS_PATH)) {
    drifts.push(`Missing registry stylesheet: ${path.relative(REPO_ROOT, REGISTRY_CSS_PATH)}`);
  } else {
    const regCss = fs.readFileSync(REGISTRY_CSS_PATH, 'utf8');
    const region = extractRegistryTokenRegion(regCss);
    if (region === null) {
      drifts.push(
        `Missing ${START_MARKER} / ${END_MARKER} markers in ${path.relative(REPO_ROOT, REGISTRY_CSS_PATH)}`,
      );
    } else if (region !== tokensCss) {
      drifts.push(
        `Token region drift between packages/tokens/src/tokens.source.json and ${path.relative(REPO_ROOT, REGISTRY_CSS_PATH)}`,
      );
    }
  }

  return drifts;
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isMain) {
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const drifts = checkTokenSync();
    if (drifts.length > 0) {
      console.error('FRAME/12 token synchronization check failed:');
      for (const d of drifts) {
        console.error(`  - ${d}`);
      }
      process.exit(1);
    }
    console.log('FRAME/12 token synchronization check passed.');
    process.exit(0);
  }

  const { tokensCss, tokensJson, indexJs, indexDts } = buildTokenArtifacts();
  fs.mkdirSync(DIST_DIR, { recursive: true });
  fs.writeFileSync(path.join(DIST_DIR, 'tokens.css'), tokensCss);
  fs.writeFileSync(path.join(DIST_DIR, 'tokens.json'), tokensJson);
  fs.writeFileSync(path.join(DIST_DIR, 'index.js'), indexJs);
  fs.writeFileSync(path.join(DIST_DIR, 'index.d.ts'), indexDts);
  fs.writeFileSync(REGISTRY_TOKENS_CSS_PATH, tokensCss);

  if (fs.existsSync(REGISTRY_CSS_PATH)) {
    const regCss = fs.readFileSync(REGISTRY_CSS_PATH, 'utf8');
    const updated = replaceRegistryTokenRegion(regCss, tokensCss);
    fs.writeFileSync(REGISTRY_CSS_PATH, updated);
  }

  console.log(
    'Built @frame12/tokens: dist/{tokens.css,tokens.json,index.js,index.d.ts}, registry/styles/frame12-tokens.css, and registry/styles/frame12.css token block.',
  );
}
